export function getRandomFal(category: FalCategory = 'all'): FalItem {
  let pool = FAL_DATABASE;
  if (category !== 'all') {
    pool = FAL_DATABASE.filter(item => item.category === category);
    if (pool.length === 0) pool = FAL_DATABASE;
  }
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}

export function formatTelegramPost(fal: FalItem, channelSignature: string = '@freeapiai'): string {
  // Format beautifully using Telegram HTML tags
  let msg = `✨ <b>${fal.title}</b> ✨\n\n`;

  if (fal.poem && fal.poem.length > 0) {
    msg += `📜 <i>«شعر و غزل»</i>\n`;
    for (let i = 0; i < fal.poem.length; i += 2) {
      if (fal.poem[i + 1]) {
        msg += `🔹 <i>${fal.poem[i]}</i>\n🔹 <i>${fal.poem[i + 1]}</i>\n\n`;
      } else {
        msg += `🔹 <i>${fal.poem[i]}</i>\n\n`;
      }
    }
  }

  msg += `🔮 <b>تعبیر و فال:</b>\n${fal.interpretation}\n\n`;
  msg += `💡 <b>پند و توصیه:</b>\n${fal.advice}\n\n`;
  msg += `🌟 <b>طالع:</b> ${fal.omen}\n`;

  if (fal.luckyColor) {
    msg += `🎨 <b>رنگ شانس:</b> ${fal.luckyColor} | 🔢 <b>عدد شانس:</b> ${fal.luckyNumber}\n`;
  }

  const cleanSignature = channelSignature.trim().startsWith('@') 
    ? channelSignature.trim() 
    : `@${channelSignature.trim()}`;

  msg += `\n━━━━━━━━━━━━━━━━━━━━\n`;
  msg += `📢 <b>کانال تلگرام:</b> <a href="https://t.me/${cleanSignature.replace('@', '')}">${cleanSignature}</a>`;

  return msg;
}
